"""Уровни доступа. Каждый следующий включает предыдущие и выдаётся пользователем отдельно,
отдельно для каждого поставщика. Проверка делается в коде скрейпера, а не только в интерфейсе."""
from enum import IntEnum


class Level(IntEnum):
    NONE = 0    # кабинеты не подключены — бот не может получать цены
    PRICES = 1  # читать каталог и цены
    CART = 2    # + добавлять товары в корзину (без оформления)
    PAY = 3     # + оформлять и оплачивать (лимит на заказ + подтверждение каждого заказа)


class PermissionDenied(Exception):
    pass


TITLES = {
    Level.NONE: "нет доступа",
    Level.PRICES: "только цены",
    Level.CART: "корзина",
    Level.PAY: "оплата",
}

DESCRIPTIONS = {
    Level.PRICES: (
        "👁 Только цены.\nБот входит в кабинет и смотрит каталог и цены. "
        "Ничего не добавляет в корзину, не оформляет и не покупает."
    ),
    Level.CART: (
        "🧺 Корзина.\nБот может добавлять товары в корзину в вашем кабинете. "
        "Оформить и оплатить заказ он не может — это остаётся за вами."
    ),
    Level.PAY: (
        "💳 Оплата.\nБот может оформить заказ и оплатить его способом, который уже сохранён "
        "в вашем кабинете у поставщика. Данные карты бот не хранит и не видит. "
        "Каждый заказ — только после вашего подтверждения суммы и не выше заданного лимита."
    ),
}


def require(granted: Level, needed: Level, action: str) -> None:
    if granted < needed:
        raise PermissionDenied(f"Для действия «{action}» нужно разрешение «{TITLES[needed]}»")
